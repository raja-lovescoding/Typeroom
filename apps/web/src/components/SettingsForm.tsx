import { useId, type ReactNode } from 'react';
import { playKeySound } from '../lib/sound.js';
import {
  CARET_STYLES,
  DEFAULT_SETTINGS,
  FONT_SIZE,
  MOTION_PREFERENCES,
  SOUND_VOLUME,
  TYPING_FONTS,
  typingFontFamily,
  updateSettings,
  useSettings,
  type MotionPreference,
  type Settings,
} from '../settings/settings.js';
import { THEMES } from '../settings/themes.js';

const MOTION_LABELS: Record<MotionPreference, { label: string; description: string }> = {
  system: { label: 'Follow system', description: "Use your device's reduce-motion setting." },
  reduce: { label: 'Reduce', description: 'No animations, glides or fades anywhere.' },
  full: { label: 'Full', description: 'Always animate, even if your device asks for less motion.' },
};

/**
 * Every client-only preference. Shared by the Settings page and the in-race overlay. Nothing here
 * reaches the server: values live in localStorage under `typeroom.settings`.
 */
export function SettingsForm() {
  const settings = useSettings();

  return <div className="settings-form">
    <Section title="Theme" description="Colours for the whole site. Hover a theme in the command palette (esc) to preview it.">
      <div className="theme-grid">
        {THEMES.map((theme) => <button
          key={theme.id}
          data-theme={theme.id}
          className={`theme-swatch ${settings.theme === theme.id ? 'active' : ''}`}
          onClick={() => updateSettings({ theme: theme.id })}
          aria-pressed={settings.theme === theme.id}
          title={theme.tags.join(', ')}
        >
          <span className="swatch-name">{theme.label}</span>
          <span className="swatch-dots" aria-hidden><i style={{ background: 'var(--accent)' }} /><i style={{ background: 'var(--text)' }} /><i style={{ background: 'var(--error)' }} /></span>
        </button>)}
      </div>
    </Section>

    <Section title="Typing font" description="The typeface of the race text. All are monospaced, so every character has the same width.">
      <div className="choice-row wrap">
        {TYPING_FONTS.map((font) => <button
          key={font.id}
          className={`choice ${settings.typingFont === font.id ? 'active' : ''}`}
          style={{ fontFamily: typingFontFamily(font.id) }}
          aria-pressed={settings.typingFont === font.id}
          onClick={() => updateSettings({ typingFont: font.id })}
        >{font.label}</button>)}
      </div>
    </Section>

    <Section title="Font size" description="Size of the race text. Larger text shows fewer words per line.">
      <div className="choice-row">
        <input
          type="range"
          min={FONT_SIZE.min}
          max={FONT_SIZE.max}
          step={FONT_SIZE.step}
          value={settings.fontSize}
          onChange={(event) => updateSettings({ fontSize: Number(event.target.value) })}
          aria-label="Typing font size"
        />
        <span className="value-pill">{settings.fontSize.toFixed(2)}rem</span>
      </div>
      <p className="font-preview" style={{ fontFamily: 'var(--typing-font)', fontSize: 'var(--typing-size)' }}>the quick brown fox</p>
    </Section>

    <Section title="Caret" description="The marker that shows where you are in the text. Other racers always use a thin line.">
      <div className="choice-row wrap">
        {CARET_STYLES.map((style) => <button
          key={style}
          className={`choice ${settings.caretStyle === style ? 'active' : ''}`}
          aria-pressed={settings.caretStyle === style}
          onClick={() => updateSettings({ caretStyle: style })}
        ><span className={`caret-sample caret-sample-${style}`} aria-hidden>a</span>{style}</button>)}
      </div>
      <Toggle setting="smoothCaret" label="Smooth caret" description="Glide between characters instead of jumping." />
    </Section>

    <Section title="While racing" description="What you see during a race.">
      <Toggle setting="liveStats" label="Live stats" description="Show your WPM and accuracy as you type. The timer and word count always show." />
      <Toggle setting="highlightErrors" label="Highlight errors" description="Keep corrected characters marked in red after you fix them." />
      <Toggle setting="ghostLabels" label="Racer name labels" description="Show names above other racers' carets." />
      <Toggle setting="focusMode" label="Focus mode" description="Fade everything but the text while you type; move the mouse to bring it back." />
    </Section>

    <Section title="Sound" description="Key clicks generated by your browser. Off by default.">
      <Toggle setting="sound" label="Typing sounds" description="A soft click for each correct key and a low tone for a mistake." />
      {settings.sound && <div className="choice-row">
        <input
          type="range"
          min={SOUND_VOLUME.min}
          max={SOUND_VOLUME.max}
          step={SOUND_VOLUME.step}
          value={settings.soundVolume}
          onChange={(event) => updateSettings({ soundVolume: Number(event.target.value) })}
          aria-label="Sound volume"
        />
        <span className="value-pill">{settings.soundVolume}%</span>
        <button className="choice" onClick={() => {
          playKeySound('correct', settings.soundVolume);
          window.setTimeout(() => playKeySound('correct', settings.soundVolume), 120);
          window.setTimeout(() => playKeySound('error', settings.soundVolume), 260);
        }}>Test</button>
      </div>}
    </Section>

    <Section title="Motion" description="Animations such as the gliding caret, countdown pulse and fades.">
      <RadioGroup
        name="motion"
        value={settings.motion}
        options={MOTION_PREFERENCES.map((value) => ({ value, ...MOTION_LABELS[value] }))}
        onChange={(motion) => updateSettings({ motion })}
      />
    </Section>

    <Section title="Reset" description="Put every setting on this page back to its default.">
      <div><button className="secondary small" onClick={() => updateSettings(DEFAULT_SETTINGS)}>Reset to defaults</button></div>
    </Section>
  </div>;
}

function Section({ title, description, children }: { title: string; description: string; children: ReactNode }) {
  return <section className="settings-section">
    <header><h3>{title}</h3><p className="muted small">{description}</p></header>
    {children}
  </section>;
}

type BooleanSetting = { [K in keyof Settings]: Settings[K] extends boolean ? K : never }[keyof Settings];

function Toggle({ setting, label, description }: { setting: BooleanSetting; label: string; description: string }) {
  const settings = useSettings();
  const on = settings[setting];
  return <label className="toggle">
    <span><strong>{label}</strong><span className="muted small">{description}</span></span>
    <input type="checkbox" role="switch" checked={on} onChange={() => updateSettings({ [setting]: !on })} />
    <span className="switch" aria-hidden />
  </label>;
}

function RadioGroup<T extends string>({ name, value, options, onChange }: {
  name: string;
  value: T;
  options: { value: T; label: string; description: string }[];
  onChange: (value: T) => void;
}) {
  const id = useId();
  return <div className="radio-list" role="radiogroup">
    {options.map((option) => <label key={option.value} className={`radio-option ${value === option.value ? 'active' : ''}`}>
      <input type="radio" name={`${id}-${name}`} checked={value === option.value} onChange={() => onChange(option.value)} />
      <span><strong>{option.label}</strong><span className="muted small">{option.description}</span></span>
    </label>)}
  </div>;
}
